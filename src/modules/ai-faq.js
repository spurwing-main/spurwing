import { animate } from "motion";

import { claimOnce, requireElement } from "../dom.js";

/**
 * Ask a question: the AI box at the top of every FAQ list.
 *
 *   <div data-ai-faq="component">
 *     <div data-ai-faq="ask">
 *       <div class="faq-card"><div class="faq-card_trigger">
 *         <textarea data-ai-faq="input">
 *         <svg data-ai-faq="sparkle">  <button data-ai-faq="send">
 *
 * The Designer owns the look: the ask card is a curated FAQ card's classes, and
 * an answer is built from those same classes, so it reads as one more card in
 * the list. This module owns the behaviour and the motion; the "Global — FAQ"
 * embed styles the few pieces only an answer has (its AI line, Remove, Cancel
 * and the Undo note).
 *
 * The box stays where it is. Each question becomes a new card straight under
 * it, newest first, so earlier answers move down rather than away. The sparkle
 * twinkles beside shimmering stage words ("Checking 6 pages…") until the answer
 * streams in, then stays as the finished card's icon, over the pages the answer
 * came from. A question asked while another is answered is answered alongside
 * it; past the Worker's 5 a minute, it waits on its card for its turn. Asking again closes the earlier answers to their questions. A finished card opens and closes like an FAQ, says the answer was
 * written by AI, and can be removed, with a few seconds to undo.
 *
 * Answers are kept in the visitor's own browser (the newest few), so they are
 * still there on the next page or the next visit. Removing one removes it only
 * there: the question stays in the Worker's log. Follow-ups only carry this
 * page view's questions, as before.
 *
 * The sparkle holds the ask card's icon slot, where an FAQ card shows its plus;
 * the send arrow takes the slot while the reader is in the box or it holds a
 * question. The Designer's CSS owns that swap, so it holds before this runs.
 *
 * Questions go to the Worker at `config.endpoint` (worker/ in this repo), which
 * answers only from spurwing.co.uk and sends server-sent events:
 *   sources  [{ title, url }]   the pages it found, before any of the answer
 *   token    "text"             the next piece of the answer
 *   cited    [{ title, url }]   the pages the finished answer drew on
 *   handoff  { message }        it couldn't answer from the site
 *   error    { message }        it couldn't answer at all
 * A hand-off offers the discovery call with the question carried into the
 * booking notes. "Report an issue" goes there the same way.
 */

export const config = {
	endpoint: "https://ask.spurwing.co.uk/ask",
	// The "spurwing-ask" Turnstile widget (invisible, spurwing.co.uk and
	// spurwing.webflow.io). Public by design; its secret lives only in the Worker.
	turnstileSiteKey: "0x4AAAAAAF2LSWTlSOLzJuaH",
	stages: ["Reading the site…", "Checking {n} pages…", "Writing an answer…"],
	// Each stage stays at least this long, so a fast answer doesn't flicker.
	minStageMs: 300,
	timeoutMs: 15000,
	// The Worker answers 5 questions a minute per connection. Past that, a
	// question waits its turn rather than failing; tries is how many times one
	// is sent when the Worker still says too many.
	perMinute: 5,
	minuteMs: 60000,
	tries: 3,
	waiting: "Waiting to send…",
	// Earlier questions and answers sent along, so a follow-up has its context.
	historyTurns: 2,
	handoffPath: "/discovery-call",
	failure: "I couldn't answer that just now.",
	handoffLink: "Ask the team directly",
	aiNote: "This answer was generated by AI.",
	report: "Report an issue",
	remove: "Remove",
	cancel: "Cancel",
	removed: "Question removed",
	undo: "Undo",
	undoMs: 7000,
	// Answers kept in the visitor's browser, newest first.
	storageKey: "spurwing-ai-faq",
	keep: 10,
};

// Spurwing's ease, from the design prototype.
const EASE = [0.2, 0.7, 0.2, 1];
// The FAQ cards' own opening (faq.js), so an answer opens like one.
const OPEN = { duration: 400, easing: "cubic-bezier(0.25, 0.1, 0.25, 1)" };

export function initAiFaq(root = document, { signal } = {}) {
	const components = root.querySelectorAll('[data-ai-faq="component"]');

	if (!components.length) return;

	const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
	const note = undoNote();

	for (const component of components) {
		if (claimOnce(component, "data-ai-faq-claimed")) setUp(component);
	}

	function setUp(component) {
		const ask = requireElement(component, '[data-ai-faq="ask"]');
		const input = requireElement(component, '[data-ai-faq="input"]');
		const send = requireElement(component, '[data-ai-faq="send"]');
		const sparkle = component.querySelector('[data-ai-faq="sparkle"]');
		const askCard = input.closest(".faq-card");
		const announcer = liveRegion(component);
		const history = [];
		// Each answer card's controls, by its element.
		const cards = new WeakMap();
		// Ties this box's follow-ups together in the log; one per page view.
		const conversation = crypto.randomUUID();

		revealWithTheList();
		if (sparkle) {
			const mark = aiMark();
			sparkle.before(mark);
			mark.prepend(sparkle);
		}

		// The answers kept from earlier, newest straight under the box, closed.
		let below = ask;
		for (const item of loadAnswers()) {
			const card = answerCard(item.question, item);
			cards.set(card.element, card);
			below.after(card.element);
			below = card.element;
		}

		// Vouch for the visitor before they ask, not after.
		const near = new IntersectionObserver(
			([entry]) => {
				if (!entry.isIntersecting) return;
				near.disconnect();
				prepareToken();
			},
			{ rootMargin: "600px 0px" },
		);
		near.observe(component);
		signal?.addEventListener("abort", () => near.disconnect());

		input.addEventListener("focus", prepareToken);
		input.addEventListener("input", fit);
		input.addEventListener("keydown", (event) => {
			if (event.key !== "Enter" || event.shiftKey || event.isComposing) return;
			event.preventDefault();
			submit();
		});
		send.addEventListener("click", submit);

		// The space an item takes in the list: its height and the gap above it.
		function room(element) {
			return element.getBoundingClientRect().height + (parseFloat(getComputedStyle(component).rowGap) || 0);
		}

		/**
		 * Something new in the list first opens its slot, on the FAQ cards' opening
		 * ease, so the page below glides down instead of jumping; then the card
		 * rises into that slot rather than out from under the box. A card leaving
		 * gives its room back.
		 */
		function makeRoom(element) {
			if (reduceMotion) return;
			const hidden = { opacity: 0, transform: "translateY(0.5rem)" };
			element.animate(
				[
					{ marginTop: `${-room(element)}px`, ...hidden, easing: OPEN.easing },
					{ marginTop: "0px", ...hidden, offset: 0.5, easing: "cubic-bezier(0.2, 0.7, 0.2, 1)" },
					{ marginTop: "0px", opacity: 1, transform: "none" },
				],
				{ duration: OPEN.duration * 2 },
			);
		}

		function giveRoom(element) {
			if (reduceMotion) return element.remove();
			const leaving = element.animate([{ opacity: 1 }, { opacity: 0, marginTop: `${-room(element)}px` }], OPEN);
			leaving.onfinish = () => element.remove();
		}

		function fit() {
			input.style.height = "auto";
			input.style.height = `${input.scrollHeight}px`;
		}

		/**
		 * The ask card reveals with the site's scroll animation on the turn after
		 * the questions above it: first when it leads the list, last when it ends
		 * it. The site's rule sets --anim-i on every data-anim element, so the turn
		 * goes on the card itself, and the sparkle inside it comes in with it.
		 */
		function revealWithTheList() {
			if (!askCard) return;
			const questions = component.parentElement?.querySelectorAll('[data-accordion="item"]') ?? [];
			const above = [...questions].filter((item) => item.compareDocumentPosition(component) & Node.DOCUMENT_POSITION_FOLLOWING);
			const turn = Math.min(above.length, 6);
			if (!askCard.hasAttribute("data-anim")) askCard.setAttribute("data-anim", "card");
			askCard.style.setProperty("--anim-i", String(turn));
		}

		async function submit() {
			const question = input.value.trim();

			if (!question) {
				input.focus();
				return;
			}
			if (answerAgain(question)) return;

			// Each question's ID is in the log, and tagged in Clarity, so the two
			// can be matched: filter Clarity's recordings by ai_faq_question_id.
			const id = crypto.randomUUID();
			window.clarity?.("set", "ai_faq_question_id", id);
			window.clarity?.("set", "ai_faq_conversation", conversation);
			track("ai_faq_ask");

			// The earlier finished answers close to their questions, as in the design.
			// One still being written stays open: several are answered at once.
			component.querySelectorAll('[data-ai-faq="answer"]').forEach((element) => cards.get(element)?.close());

			// The box clears and stays, so the next question can be typed while this
			// one is answered. Focus stays in it; the status region reads the answer.
			const card = answerCard(question);
			cards.set(card.element, card);
			ask.after(card.element);
			makeRoom(card.element);
			input.value = "";
			input.style.height = "";
			announce(config.stages[2]);
			card.open();

			const answer = await stream(question, card, id);

			// Cancelled, or the page went: the card has nothing to keep.
			if (answer === null) {
				if (!signal?.aborted) giveRoom(card.element);
				announcer.querySelector("[data-ai-faq-note]")?.remove();
				return;
			}

			card.finish();
			// Read once, whole: announced word by word as it streams, a screen
			// reader missed the start and spoke the rest in fragments.
			announce(card.spoken(), true);

			if (answer) {
				history.push({ role: "user", content: question }, { role: "assistant", content: answer });
				history.splice(0, Math.max(0, history.length - config.historyTurns * 2));
				const item = { id, question, answer, pages: card.pages() };
				keepAnswer(item);
				card.keep(item);
			}

			if (signal?.aborted) return;
			prepareToken();
		}

		/**
		 * A question this page already answers isn't asked again. A written FAQ
		 * that matches opens where it is; an earlier AI answer moves back under the
		 * box and opens. Matching is by words, ignoring case and punctuation: the
		 * same words, or one more or fewer, count. One word swapped for another
		 * doesn't ("website" for "migration"), so different questions still go.
		 */
		function answerAgain(question) {
			const written = [...(component.parentElement?.querySelectorAll('[data-accordion="item"]') ?? [])].find((item) =>
				sameQuestion(question, item.querySelector('[data-accordion="trigger"]')?.textContent ?? ""),
			);
			const earlier = [...component.querySelectorAll('[data-ai-faq="answer"]:not([aria-busy])')].find((element) =>
				sameQuestion(question, cards.get(element)?.question ?? ""),
			);
			if (!written && !earlier) return false;

			input.value = "";
			input.style.height = "";
			if (written) {
				track("ai_faq_written");
				if (written.dataset.accordionOpen !== "true") written.querySelector('[data-accordion="trigger"]').click();
				written.scrollIntoView({ behavior: reduceMotion ? "auto" : "smooth", block: "nearest" });
				announce(written.querySelector('[data-accordion="content"]')?.textContent.trim() ?? "", true);
				return true;
			}

			track("ai_faq_repeat");
			const card = cards.get(earlier);
			component.querySelectorAll('[data-ai-faq="answer"]').forEach((element) => element !== earlier && cards.get(element)?.close());
			if (ask.nextElementSibling !== earlier) {
				ask.after(earlier);
				makeRoom(earlier);
			}
			card?.reopen();
			if (card?.kept()) keepAnswer(card.kept());
			announce(card?.spoken() ?? "", true);
			return true;
		}

		/**
		 * "Writing an answer…" replaces whatever was said before. A finished answer
		 * is added after the others instead, so two finishing together are both
		 * read, one after the other.
		 */
		function announce(message, answer = false) {
			if (answer) announcer.querySelector("[data-ai-faq-note]")?.remove();
			else announcer.replaceChildren();
			const line = node("p");
			line.textContent = message;
			if (!answer) line.dataset.aiFaqNote = "";
			announcer.append(line);
		}

		/** The answer as text, "" after a hand-off, or null when cancelled or the page went. */
		async function stream(question, card, id) {
			const controller = new AbortController();
			let cancelled = false;
			const stop = () => controller.abort();
			signal?.addEventListener("abort", stop);
			card.onCancel(() => {
				cancelled = true;
				track("ai_faq_cancel");
				stop();
			});
			let timeout;
			let answer = "";

			try {
				let response;
				for (let tries = 1; ; tries++) {
					await turn(card, controller.signal);
					timeout = setTimeout(stop, config.timeoutMs);
					response = await post(question, id, controller.signal);
					if (response.status !== 429 || tries === config.tries) break;
					// Too many from this connection, which others may share: the minute
					// counts as used, and the question waits for the next one.
					clearTimeout(timeout);
					sent.splice(0, sent.length, ...Array(config.perMinute).fill(Date.now()));
				}
				if (!response.ok || !response.body) throw new Error(`ask failed: ${response.status}`);

				for await (const { event, data } of readEvents(response.body)) {
					if (event === "sources") {
						card.cite(data);
						await card.stage(1, data.length);
						card.stage(2);
					} else if (event === "cited") {
						card.cite(data);
					} else if (event === "token") {
						await card.write(data);
						answer += data;
					} else if (event === "handoff") {
						card.handoff(data.message, question);
						track("ai_faq_no_answer");
						return "";
					} else if (event === "error") {
						throw new Error(data.message);
					}
				}

				track("ai_faq_answered");
				return answer;
			} catch {
				if (signal?.aborted || cancelled) return null;
				card.handoff(config.failure, question);
				track("ai_faq_no_answer");
				return "";
			} finally {
				clearTimeout(timeout);
				signal?.removeEventListener("abort", stop);
			}
		}

		async function post(question, id, abort) {
			return fetch(config.endpoint, {
				method: "POST",
				headers: { "content-type": "application/json" },
				body: JSON.stringify({
					question,
					history,
					page: location.pathname,
					id,
					conversation,
					clarity: clarityIds(),
					token: await turnstileToken(),
				}),
				signal: abort,
			});
		}

		// The sparkle with "AI" at its top right, as in Paul's demo.
		function aiMark() {
			const mark = node("span", "ai-faq_mark");
			const label = node("span", "ai-faq_label");
			mark.setAttribute("aria-hidden", "true");
			label.textContent = "AI";
			mark.append(label);
			return mark;
		}

		/**
		 * One answer card, built from the classes a curated FAQ card carries so the
		 * Designer's styles apply, in its shape: a heading around a button row. It
		 * isn't an accordion item and isn't marked up as a published FAQ: the AI's
		 * answers are never presented to Google as ours. Given a `saved` answer, it
		 * is built finished and closed, with no motion.
		 */
		function answerCard(question, saved) {
			const element = node("div", "faq-card");
			const heading = node("h3", "faq-card_title");
			const head = node("button", "faq-card_trigger");
			const title = node("span");
			const status = node("span", "faq-card_icon");
			const panel = node("div", "faq-card_panel");
			const content = node("div", "faq-card_content");
			const body = node("div", "rich-text w-richtext");
			const meta = node("div", "ai-faq_meta");
			const text = node("p");
			let paragraph = text;
			let twinkle = [];
			let shimmer = null;
			let pages = saved?.pages ?? [];
			let shownAt = 0;
			let writing = false;
			let done = false;
			let handedOff = false;
			let held = false;
			let open = true;
			let cancel = () => {};
			// The browser's copy of this answer, once there is one.
			let kept = saved ?? null;

			element.dataset.aiFaq = "answer";
			head.type = "button";
			head.setAttribute("aria-expanded", "true");
			content.id = `ai-faq-answer-${crypto.randomUUID()}`;
			head.setAttribute("aria-controls", content.id);
			title.textContent = question;
			head.append(title, status);
			heading.append(head);
			body.append(text);
			content.append(body, meta);
			panel.append(content);
			element.append(heading, panel);

			head.addEventListener("click", () => {
				if (done) toggle(!open);
			});

			// The thinking star is the ask card's own sparkle, twinkling as in the
			// design: each star shrinks, turns and dims in turn.
			if (sparkle) {
				const star = sparkle.cloneNode(true);
				star.removeAttribute("class");
				star.removeAttribute("data-ai-faq");
				star.removeAttribute("style");
				star.removeAttribute("width");
				star.removeAttribute("height");
				// Drawn at the question's 22px, as in the design, over the 16px icon
				// slot; the negative margin keeps it centred there.
				Object.assign(star.style, { display: "block", width: "100%", height: "100%" });
				const mark = aiMark();
				mark.prepend(star);
				Object.assign(mark.style, { width: "1.375rem", height: "1.375rem", margin: "-0.1875rem" });
				status.append(mark);
				if (!reduceMotion && !saved) {
					twinkle = [...star.querySelectorAll("path")].map((path, index) => {
						path.style.transformBox = "fill-box";
						path.style.transformOrigin = "center";
						return animate(
							path,
							{ scale: [1, 0.55, 1], rotate: [0, 45, 0], opacity: [1, 0.35, 1] },
							{ duration: 1.2, delay: index * 0.2, ease: "easeInOut", repeat: Infinity },
						);
					});
				}
			}

			if (saved) {
				writeAll(saved.answer);
				settleCard();
				toggle(false, true);
			} else {
				element.setAttribute("aria-busy", "true");
				const button = node("button", "ai-faq_cancel");
				button.type = "button";
				button.textContent = config.cancel;
				button.addEventListener("click", () => cancel());
				meta.append(button);
				show(0);
			}

			// Opens like an FAQ answer, the first words rising into it.
			function begin() {
				resize(() => {}, 0);
				rise(text, 0.1);
			}

			/**
			 * Every change in the card's height eases like an FAQ answer opening: a
			 * new line, the hand-off, the sources. The panel goes from the height it
			 * shows now to the one its content needs. This is the browser's own
			 * animation, which starts on the frame it's asked for; a Motion height
			 * tween showed the card fully open for a frame, then fell behind and
			 * snapped.
			 */
			function resize(change, from = panel.getBoundingClientRect().height) {
				change();
				if (reduceMotion || !open) return;
				const to = content.offsetHeight;
				if (Math.abs(to - from) < 1) return;
				panel.animate([{ height: `${from}px` }, { height: `${to}px` }], OPEN);
			}

			// Opens and closes like an FAQ answer. A closed answer is out of the tab
			// order and hidden from screen readers, as faq.js does.
			function toggle(next, immediate = false) {
				const from = panel.getBoundingClientRect().height;
				open = next;
				head.setAttribute("aria-expanded", String(open));
				panel.style.height = open ? "" : "0px";
				content.inert = !open;
				if (immediate || reduceMotion) return;
				panel.animate([{ height: `${from}px` }, { height: `${open ? content.offsetHeight : 0}px` }], OPEN);
			}

			// Waits out the stage on screen first, so a fast answer doesn't flicker
			// through words nobody could read.
			async function stage(index, count = pages.length) {
				await settle();
				if (writing) return;
				show(index, count);
				if (!reduceMotion) animate(text, { opacity: [0.3, 1] }, { duration: 0.3 });
			}

			// Straight away, not after a wait, so the first stage is in place before
			// the card measures itself to open.
			function show(index, count = pages.length) {
				text.textContent = config.stages[index].replace("{n}", count);
				startShimmer();
				shownAt = Date.now();
			}

			// Waiting its turn to be sent, then back to the first stage once it is.
			function hold() {
				if (held) return;
				held = true;
				track("ai_faq_wait");
				text.textContent = config.waiting;
				startShimmer();
				shownAt = Date.now();
			}

			function release() {
				if (!held) return;
				held = false;
				show(0);
			}

			function settle() {
				return pause(shownAt + config.minStageMs - Date.now());
			}

			// A light sweeping across the stage words, as in the design.
			function startShimmer() {
				if (reduceMotion || shimmer) return;
				Object.assign(text.style, {
					backgroundImage:
						"linear-gradient(90deg, var(--_color---grey-500) 0%, var(--_color---grey-500) 38%, var(--_color---grey-950) 50%, var(--_color---grey-500) 62%, var(--_color---grey-500) 100%)",
					backgroundSize: "300% 100%",
					backgroundClip: "text",
					webkitBackgroundClip: "text",
					color: "transparent",
				});
				shimmer = animate(text, { backgroundPosition: ["100% 0", "0% 0"] }, { duration: 1.2, ease: "linear", repeat: Infinity });
			}

			function stopShimmer() {
				shimmer?.stop();
				shimmer = null;
				text.removeAttribute("style");
			}

			async function write(piece) {
				const first = !writing;
				if (first) {
					await settle();
					writing = true;
					stopShimmer();
				}
				// A blank line in the answer starts a new paragraph.
				resize(() => {
					if (first) text.textContent = "";
					writeAll(piece, !reduceMotion);
				});
			}

			function writeAll(piece, fade = false) {
				piece.split(/\n{2,}/).forEach((part, index) => {
					if (index) {
						paragraph = node("p");
						body.append(paragraph);
					}
					if (!part) return;
					const words = node("span");
					words.textContent = part;
					paragraph.append(words);
					if (fade) animate(words, { opacity: [0, 1] }, { duration: 0.25 });
				});
			}

			function cite(list) {
				pages = list;
			}

			function handoff(message, asked) {
				writing = true;
				handedOff = true;
				stopShimmer();
				pages = [];
				const link = node("a", "text-style-link");
				link.href = discoveryLink(asked);
				link.textContent = config.handoffLink;
				link.addEventListener("click", () => track("ai_faq_handoff"));
				resize(() => {
					text.textContent = `${message} `;
					text.append(link, ".");
				});
				rise(text);
			}

			// The star stops twinkling and settles as the card's icon, and the
			// pages it drew on and the AI line rise in underneath.
			function finish() {
				writing = true;
				stopShimmer();
				twinkle.forEach((controls) => controls.stop());
				const paths = [...status.querySelectorAll("path")];
				if (paths.length && !reduceMotion) animate(paths, { scale: 1, rotate: 0, opacity: 1 }, { duration: 0.35, ease: EASE });
				element.removeAttribute("aria-busy");
				resize(settleCard);
				rise(meta);
			}

			// The finished card: its sources, then the AI line and Remove in place of Cancel.
			function settleCard() {
				done = true;
				if (pages.length) {
					const from = node("p");
					from.dataset.aiFaqSources = "";
					from.append("From: ");
					pages.forEach((page, index) => {
						const link = node("a", "text-style-link");
						link.href = page.url;
						link.textContent = page.title;
						from.append(...(index ? [", ", link] : [link]));
					});
					body.append(from);
				}

				meta.replaceChildren();
				if (!handedOff) {
					const line = node("p", "ai-faq_note");
					const report = node("a", "ai-faq_report");
					report.href = discoveryLink(question);
					report.textContent = config.report;
					report.addEventListener("click", () => track("ai_faq_report"));
					line.append(`${config.aiNote} `, report, ".");
					if (sparkle) {
						const icon = sparkle.cloneNode(true);
						icon.removeAttribute("data-ai-faq");
						icon.removeAttribute("style");
						icon.setAttribute("class", "ai-faq_note-icon");
						line.prepend(icon);
					}
					meta.append(line);
				}
				const remove = node("button", "ai-faq_remove");
				remove.type = "button";
				remove.textContent = config.remove;
				remove.setAttribute("aria-label", `${config.remove}: ${question}`);
				remove.addEventListener("click", removeCard);
				meta.append(remove);
			}

			/**
			 * Gone from the page and the browser's copy, with a few seconds to undo.
			 * Focus goes back to the box, so it doesn't drop to the top of the page.
			 */
			function removeCard() {
				const place = element.previousElementSibling;
				const order = kept ? loadAnswers().findIndex((item) => item.id === kept.id) : -1;
				if (kept) forgetAnswer(kept.id);
				giveRoom(element);
				input.focus({ preventScroll: true });
				track("ai_faq_remove");
				note.show(config.removed, () => {
					element.getAnimations().forEach((running) => running.cancel());
					element.removeAttribute("style");
					(place?.isConnected ? place : ask).after(element);
					makeRoom(element);
					if (kept) keepAnswer(kept, Math.max(order, 0));
				});
			}

			// What a screen reader hears once the card is done: the answer, or the
			// hand-off, without the stage words or the sources line.
			function spoken() {
				return [...body.querySelectorAll("p")]
					.filter((p) => !p.hasAttribute("data-ai-faq-sources"))
					.map((p) => p.textContent.trim())
					.filter(Boolean)
					.join(" ");
			}

			return {
				element,
				heading,
				question,
				open: begin,
				stage,
				hold,
				release,
				write,
				cite,
				handoff,
				finish,
				spoken,
				pages: () => pages,
				close: () => done && open && toggle(false),
				reopen: () => done && !open && toggle(true),
				kept: () => kept,
				onCancel: (stop) => (cancel = stop),
				keep: (item) => (kept = item),
			};
		}
	}

	/**
	 * One note for the page, "Question removed · Undo", shown for a few seconds
	 * after a removal. A second removal replaces the first: only the latest can
	 * be undone. It shows in the browser's top layer: on a phone the cookie
	 * banner sits where the note does, in a layer no z-index gets above.
	 */
	function undoNote() {
		const box = node("div", "ai-faq_toast");
		const label = node("span");
		const button = node("button", "ai-faq_undo");
		let timer;
		let undo = null;
		box.setAttribute("role", "status");
		box.popover = "manual";
		box.hidden = true;
		button.type = "button";
		button.textContent = config.undo;
		box.append(label, button);
		button.addEventListener("click", () => {
			undo?.();
			hide();
		});
		signal?.addEventListener("abort", () => {
			clearTimeout(timer);
			box.remove();
		});

		function hide() {
			clearTimeout(timer);
			undo = null;
			if (box.matches?.(":popover-open")) box.hidePopover();
			box.hidden = true;
		}

		return {
			show(message, action) {
				if (!box.isConnected) document.body.append(box);
				clearTimeout(timer);
				undo = action;
				label.textContent = message;
				box.hidden = false;
				if (box.showPopover && !box.matches(":popover-open")) box.showPopover();
				rise(box);
				timer = setTimeout(hide, config.undoMs);
			},
		};
	}

	// One polite status per box, there from the start: a region created along
	// with its message is often not heard at all.
	// Hidden by the site's u-visually-hidden utility (the base embed).
	function liveRegion(component) {
		const region = node("div", "u-visually-hidden");
		region.setAttribute("role", "status");
		component.append(region);
		return region;
	}

	// The design's fade-up: in from 8px below, on Spurwing's ease.
	function rise(element, delay = 0) {
		if (reduceMotion) return;
		animate(element, { opacity: [0, 1], y: [8, 0] }, { duration: 0.4, delay, ease: EASE });
	}
}

// When this page's latest questions were sent, oldest first: a minute's worth
// at most, across every box on the page.
const sent = [];

/**
 * Waits until this page has sent fewer than the Worker's minute allows, then
 * counts the question as sent. A question that has to wait says so on its card.
 */
async function turn(card, abort) {
	for (;;) {
		abort.throwIfAborted();
		const now = Date.now();
		while (sent.length && now - sent[0] >= config.minuteMs) sent.shift();
		if (sent.length < config.perMinute) {
			sent.push(now);
			card.release();
			return;
		}
		card.hold();
		await new Promise((resolve, reject) => {
			const timer = setTimeout(resolve, sent[0] + config.minuteMs - now);
			abort.addEventListener("abort", () => (clearTimeout(timer), reject(abort.reason)), { once: true });
		});
	}
}

/** Parse a server-sent event stream into { event, data } pairs, data JSON-decoded. */
export async function* readEvents(body) {
	const reader = body.getReader();
	const decoder = new TextDecoder();
	let buffer = "";

	for (;;) {
		const { done, value } = await reader.read();
		buffer += decoder.decode(value, { stream: !done });

		let end;
		while ((end = buffer.indexOf("\n\n")) !== -1) {
			const block = buffer.slice(0, end);
			buffer = buffer.slice(end + 2);

			let event = "message";
			const data = [];
			for (const line of block.split("\n")) {
				if (line.startsWith("event:")) event = line.slice(6).trim();
				else if (line.startsWith("data:")) data.push(line.slice(5).trimStart());
			}
			if (data.length) yield { event, data: JSON.parse(data.join("\n")) };
		}

		if (done) return;
	}
}

/** The same question: the same words, ignoring case and punctuation, or one more or fewer. */
export function sameQuestion(a, b) {
	const words = (text) => new Set(text.toLowerCase().match(/[\p{L}\p{N}]+/gu) ?? []);
	const one = words(a);
	const two = words(b);
	if (!one.size || !two.size) return false;
	const shared = [...one].filter((word) => two.has(word)).length;
	return shared / (one.size + two.size - shared) >= 0.8;
}

function discoveryLink(question) {
	return `${config.handoffPath}?notes=${encodeURIComponent(question)}`;
}

/**
 * The answers kept in this browser, newest first. Storage can be refused (a
 * private window, blocked site data), and then nothing is kept: the box still
 * answers, it just forgets on the next page.
 */
export function loadAnswers() {
	try {
		const list = JSON.parse(localStorage.getItem(config.storageKey) || "[]");
		return Array.isArray(list) ? list.filter((item) => typeof item?.question === "string" && typeof item.answer === "string") : [];
	} catch {
		return [];
	}
}

function saveAnswers(list) {
	try {
		localStorage.setItem(config.storageKey, JSON.stringify(list.slice(0, config.keep)));
	} catch {
		// Refused: see loadAnswers.
	}
}

function keepAnswer(item, at = 0) {
	const list = loadAnswers().filter((kept) => kept.id !== item.id);
	list.splice(at, 0, item);
	saveAnswers(list);
}

function forgetAnswer(id) {
	saveAnswers(loadAnswers().filter((item) => item.id !== id));
}

function node(tag, className) {
	const element = document.createElement(tag);
	if (className) element.className = className;
	return element;
}

function pause(ms) {
	return ms > 0 ? new Promise((resolve) => setTimeout(resolve, ms)) : Promise.resolve();
}

// Clarity loads only after cookie consent, so before then there is nothing to tell.
function track(name) {
	window.clarity?.("event", name);
}

// Clarity's own visitor and session IDs, from its cookies (the first part of
// _clck and _clsk, split on ^ as Clarity writes them today, or |), so a logged question can be found in its recording. Empty
// until the visitor accepts cookies.
export function clarityIds() {
	const first = (name) => {
		const value = document.cookie
			.split("; ")
			.find((cookie) => cookie.startsWith(`${name}=`))
			?.slice(name.length + 1);
		return value ? decodeURIComponent(value).split(/[|^]/)[0] : "";
	};
	return { user: first("_clck"), session: first("_clsk") };
}

// Turnstile takes about two seconds to vouch for a visitor. It starts as the
// box comes near the screen and again after each question, so a token is
// waiting by the time anyone presses Enter. Tokens are single-use and last five
// minutes; an older one is fetched again.
const TOKEN_LIFE_MS = 4 * 60 * 1000;
let turnstile;
let ready = null;

export function prepareToken() {
	if (!config.turnstileSiteKey) return;
	if (ready && Date.now() - ready.at < TOKEN_LIFE_MS) return;
	const token = fetchToken();
	token.catch(() => {});
	ready = { token, at: Date.now() };
}

function turnstileToken() {
	if (!config.turnstileSiteKey) return Promise.resolve("");
	prepareToken();
	const { token } = ready;
	ready = null;
	return token;
}

function fetchToken() {
	turnstile ??= new Promise((resolve, reject) => {
		const script = document.createElement("script");
		script.src = "https://challenges.cloudflare.com/turnstile/v0/api.js?render=explicit";
		script.onload = () => resolve(window.turnstile);
		script.onerror = reject;
		document.head.append(script);
	});

	return turnstile.then(
		(api) =>
			new Promise((resolve, reject) => {
				const holder = document.createElement("div");
				document.body.append(holder);
				api.render(holder, {
					sitekey: config.turnstileSiteKey,
					callback: (token) => {
						holder.remove();
						resolve(token);
					},
					"error-callback": () => {
						holder.remove();
						reject(new Error("turnstile failed"));
					},
				});
			}),
	);
}
